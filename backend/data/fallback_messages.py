def get_fallback_message(threat_level: int) -> str:
    """
    Returns an appropriate fallback message based on threat level.
    Level 1: Humorous
    Level 2: Firm
    Level 3-4: Threatening
    """
    import random
    
    if threat_level <= 1:
        return random.choice(LEVEL_1_MESSAGES)
    elif threat_level == 2:
        return random.choice(LEVEL_2_MESSAGES)
    else:  # Level 3 or 4
        return random.choice(LEVEL_3_4_MESSAGES)
